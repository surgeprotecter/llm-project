from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class ItineraryDay(BaseModel):
    day: int
    title: str
    activities: list[dict[str, Any]] = Field(default_factory=list)
    estimated_cost: float | None = None


class TravelPlan(BaseModel):
    trip_id: str
    title: str
    summary: str
    destination: str | None = None
    assumptions: list[str] = Field(default_factory=list)
    itinerary: list[ItineraryDay] = Field(default_factory=list)
    weather: dict[str, Any] = Field(default_factory=dict)
    research_notes: list[dict[str, Any]] = Field(default_factory=list)
    hotel_options: list[dict[str, Any]] = Field(default_factory=list)
    transport_options: list[dict[str, Any]] = Field(default_factory=list)
    budget_breakdown: dict[str, float] = Field(default_factory=dict)
    total_estimated_cost: float | None = None
    evidence_ids: list[str] = Field(default_factory=list)
    sources: list[dict[str, Any]] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    # Structured content for the approved standard layout. Values carry their
    # own evidence/status; HTML is rendered locally, never generated by the LLM.
    report: dict[str, Any] = Field(default_factory=dict)
